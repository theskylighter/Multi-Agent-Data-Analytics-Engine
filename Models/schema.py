from pydantic import BaseModel, Field
from typing import Annotated,Literal
from operator import add

class AgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by  the agent" )
    user_question :str = Field(...,description="The original question asked by the user")
    curated_ques : str = Field(..., description="Curated User Question")
    prompt_query_context : str = Field( ..., description="A detailed  prompt with SQL DB context that will ")
    is_safe : Literal["Yes", "No"] =Field(...,)
    comments : str = Field(..., description="Additional comments or feedback from the judge regarding the safety of the SQL query")
    generated_sql_query : str = Field( ..., description="SQL query generated by the agent based on the curated question and prompt context  ")
    sql_query_execution_result : str = Field( ..., description="SQL query execution result fetched from the database based on the generated SQL query")
    final_answer: str = Field (..., description="The Final Answer generated by the ag ent based on the SQL")
    
class JudgeSchema(BaseModel):
    answer : Literal["Yes","No"] = Field(..., description="Indicates whether the SQL query generated by the agent is safe to execute or not")
    comments : str = Field(..., description="Additional comments or feedback from the judge regarding the safety of the SQL query")

class ETLAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field ( ..., description="List of messages to be processed by the ETL Agent")

class RouterSchema(BaseModel):
    answer : Literal["sql","etl"] = Field(..., description="Indicates whether the query is related to SQL or ETL")
    comments : str = Field(..., description="Additional comments or feedback from the Data Agent regarding the query")

class DataAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(default_factory=list, description="List of messages to be processed by the Data Agent")
    route_response: str = Field(default="", description="The response from the router indicating the type of query")
    comments: str = Field(default="", description="Additional comments or feedback from the Data Agent regarding the query")